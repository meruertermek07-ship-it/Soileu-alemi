// Әр дыбыс пен кезеңге 10 жеке тапсырма жасалады.
function buildTasks(sound, stageIndex) {
  return stageTasks[stageIndex].map((title, i) => {
    const word = sound.words[i];
    const syllable = sound.syllables[i];

    let task = {
      id: `${sound.letter}-${stageIndex + 1}-${i + 1}`,
      number: i + 1,
      title,
      sound: sound.letter,
      word,
      syllable,
      icon: ["🎯", "⭐", "🎈", "🧩", "🎨"][i % 5],
      animation: ["bounce", "float", "pulse", "wiggle", "sparkle"][i % 5],
      type: "say",
      question: "",
      options: [],
      answer: "",
      instruction: ""
    };

    if (stageIndex === 0) {
      task.instruction = [
        "Айнаға қарап жаттығуды орында.",
        "Қимылды асықпай қайтала.",
        "Ерін мен тілдің қозғалысын бақыла.",
        "Дыбысты тыңдап, қайталап көр.",
        "Сөзді анық айтып көр."
      ][i % 5];

      task.question = `${sound.letter} дыбысына дайындалу жаттығуы.`;
      task.type = "say";
    }

    if (stageIndex === 1) {
      task.type = "say";
      task.question = `${syllable} буынын анық қайтала.`;
      task.instruction = `Алдымен тыңда, содан кейін ${syllable} деп айтып көр.`;
    }

    if (stageIndex === 2) {
      task.type = "say";
      task.question = `«${word}» сөзін айт.`;
      task.instruction = `Сөзді анық айтып, ${sound.letter} дыбысына назар аудар.`;
    }

    if (stageIndex === 3) {
      task.type = "choice";

      const distractors = soundData
        .filter(s => s.letter !== sound.letter)
        .flatMap(s => s.words)
        .slice(i, i + 3);

      task.options = [
        word,
        ...distractors.slice(0, 3)
      ].sort(() => Math.random() - 0.5);

      task.answer = word;
      task.question = `Қай сөзде ${sound.letter} дыбысы бар?`;
      task.instruction = "Дұрыс жауапты таңда.";
    }

    return task;
  });
}

const programData = soundData.map(sound => ({
  ...sound,
  stages: stageNames.map((name, index) => ({
    title: name,
    tasks: buildTasks(sound, index)
  }))
}));


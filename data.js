function createSoundTasks(info, stageIndex) {
const templates = STAGE_TASKS[stageIndex];

return templates.map((template, taskIndex) => {
const word = info.words[taskIndex % info.words.length];
const syllable = info.syllables[taskIndex % info.syllables.length];
const sentence = info.sentences[taskIndex % info.sentences.length];

let example = template.example;
if (stageIndex === 0) {
  example += ` Мысал сөз: ${word}.`;
}
if (stageIndex === 1) {
  example += ` Буын үлгісі: ${syllable}. Сөз: ${word}.`;
}
if (stageIndex === 2) {
  example += ` Сөз: ${word}. Сөйлем: ${sentence}`;
}
if (stageIndex === 3) {
  example += ` Сөз: ${word}. Салыстырылатын дыбыстар: ${info.opposites.join(", ")}.`;
}
let visual;
if (stageIndex === 0) {
  visual = [
    info.emoji,
    "🪞 Айна",
    "👄 Артикуляциялық жаттығу",
    word
  ];
} else if (stageIndex === 1) {
  visual = [
    info.emoji,
    syllable,
    word,
    "👄 Артикуляциялық қалып"
  ];
} else if (stageIndex === 2) {
  visual = [
    info.emoji,
    word,
    sentence,
    "🗣️ Сөйлеу жаттығуы"
  ];
} else {
  visual = [
    info.emoji,
    ...info.opposites,
    word,
    "👂 Тыңда және ажырат"
  ];
}
return {
  id: `${info.sound}_${stageIndex + 1}_${taskIndex + 1}`,
  title: `${template.title} — ${info.sound} дыбысы`,
  goal:
    `${template.goal} ${info.sound} дыбысын дұрыс айту дағдысын дамыту.`,
  instruction:
    `${template.instruction} ${info.sound} дыбысына назар аудар.`,
  example,
  visual,
  words: [
    word,
    ...info.words.slice(0, 3)
  ],
  syllables: info.syllables,
  sentences: info.sentences,
  check:
    `Өзіңді тексер: ${info.sound} дыбысын анық айттың ба? ` +
    `Тіл мен еріннің қалпын бақыладың ба?`,
  hint:
    `${info.articulation} ` +
    `Қажет болса, логопедтің үлгісін қайта тыңда.`,
  camera: stageIndex === 0 || stageIndex === 1,
  microphone: stageIndex === 1 || stageIndex === 2,
  breathing: stageIndex === 0 && taskIndex === 4
};

});
}


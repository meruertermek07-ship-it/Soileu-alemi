function createSoundTasks(soundInfo, stageIndex) {
    const templates = TASK_TEMPLATES[stageIndex];
    return templates.map((template, index) => {
        const taskNumber = index + 1;
        let examples = [];
        if (stageIndex === 0) {
            examples = soundInfo.preparation;
        }
        if (stageIndex === 1) {
            examples = soundInfo.syllables;
        }
        if (stageIndex === 2) {
            examples = soundInfo.words;
        }
        if (stageIndex === 3) {
            examples = soundInfo.contrastWords.map(pair =>
                pair.join(" — ")
            );
        }
        const example = examples[index % examples.length];
        return {
            id: `${soundInfo.key}-ST${stageIndex + 1}-T${taskNumber}`,
            number: taskNumber,
            sound: soundInfo.sound,
            stage: stageIndex + 1,
            title: template.title,
            goal: template.goal,
            instruction: template.instruction,
            example: example,
            examples: examples,
            words: soundInfo.words,
            syllables: soundInfo.syllables,
            sentences: soundInfo.sentences,
            preparation: soundInfo.preparation,
            contrastWords: soundInfo.contrastWords,
            articulation: soundInfo.articulation,
            type: template.type,
            visual: {
                emoji: soundInfo.emoji,
                sound: soundInfo.sound,
                world: soundInfo.world,
                color: soundInfo.color
            },
            assessment: [
                {
                    score: 3,
                    label: "Өздігінен орындады"
                },
                {
                    score: 2,
                    label: "Аздаған көмекпен орындады"
                },
                {
                    score: 1,
                    label: "Көп көмекті қажет етті"
                },
                {
                    score: 0,
                    label: "Қайталау қажет"
                }
            ],
            cameraEnabled: true,
            microphoneEnabled: true,
            videoSearch:
                `${soundInfo.sound} дыбысы логопедиялық жаттығу ${template.title}`,
            completed: false
        };
    });
}
